export const getSpritePixelColor = (val, rgb, shade, isHurt) => {
  if (val === 0) return null;
  const r = rgb.r, g = rgb.g, b = rgb.b;
  switch (val) {
    case 1:
      return `rgb(${Math.floor(r * shade)}, ${Math.floor(g * shade)}, ${Math.floor(b * shade)})`;
    case 2:
      return `rgb(${Math.floor(r * shade * 0.35)}, ${Math.floor(g * shade * 0.35)}, ${Math.floor(b * shade * 0.35)})`;
    case 3:
      if (isHurt) return `rgb(255, ${Math.floor(100 * shade)}, ${Math.floor(80 * shade)})`;
      return `rgb(${Math.min(255, Math.floor(r * shade * 1.3))}, ${Math.min(255, Math.floor(g * shade * 1.3))}, ${Math.min(255, Math.floor(b * shade * 1.3))})`;
    case 4:
      if (isHurt) return '#ff2200';
      return '#ff4444';
    case 5:
      return `rgb(${Math.floor(140 * shade)}, ${Math.floor(130 * shade)}, ${Math.floor(120 * shade)})`;
    default:
      return null;
  }
};
